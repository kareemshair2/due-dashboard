/**
 * Writes js/config.js for CI / GitHub Pages builds.
 *
 * The local config is intentionally gitignored because the Apps Script URL is
 * a bearer URL. CI reads it from repository variables instead.
 *
 * Required environment variables:
 *   DUE_SPREADSHEET_ID
 *   DUE_PROVIDER            "apps-script" (default) or "gviz"
 *   DUE_APPS_SCRIPT_URL     required when DUE_PROVIDER=apps-script
 *
 * Optional:
 *   DUE_SHEET_ORDERS, DUE_SHEET_BRANCHES, DUE_SHEET_CARS
 */

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "js/config.js");

const spreadsheetId = (process.env.DUE_SPREADSHEET_ID || "").trim();
const provider = (process.env.DUE_PROVIDER || "apps-script").trim();
const appsScriptUrl = (process.env.DUE_APPS_SCRIPT_URL || "").trim();

if (!spreadsheetId) {
  console.error("DUE_SPREADSHEET_ID is required to generate js/config.js.");
  process.exit(1);
}

if (!["apps-script", "gviz"].includes(provider)) {
  console.error('DUE_PROVIDER must be "apps-script" or "gviz".');
  process.exit(1);
}

if (provider === "apps-script" && !/^https:\/\/script\.google\.com\/macros\/s\/.+\/exec$/.test(appsScriptUrl)) {
  console.error(
    "DUE_APPS_SCRIPT_URL is required when DUE_PROVIDER=apps-script, and must be a deployed /exec URL.",
  );
  process.exit(1);
}

const config = {
  provider,
  spreadsheetId,
  appsScriptUrl,
  sheetNames: {
    orders: (process.env.DUE_SHEET_ORDERS || "Orders").trim(),
    branches: (process.env.DUE_SHEET_BRANCHES || "BRANCHES&AGENTS").trim(),
    cars: (process.env.DUE_SHEET_CARS || "Cars").trim(),
  },
  exceptionalBranches: ["Hold", "HOLD", "معلق"],
  statusAliases: {
    pickUp: ["PICK UP", "PICKUP", "PICK-UP", "بيك اب"],
    hold: ["HOLD", "Hold", "معلق"],
  },
  dateOrder: "DMY",
  currency: "EGP",
  locale: "ar-EG",
  autoRefreshMinutes: 0,
  cacheTtlMinutes: 15,
};

const body = `/**
 * Generated by scripts/generate-config.mjs for a CI build.
 * Do not edit this file by hand; change the repository variables instead.
 */
export const config = ${JSON.stringify(config, null, 2)};
`;

writeFileSync(target, body, "utf8");
console.log(`Wrote ${target} (provider: ${provider}).`);
